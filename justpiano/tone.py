def _merge_voicings(specs: dict[str, dict[str, object]]) -> dict[str, dict]:
    """Fill every voicing out to a complete parameter set.

    The literals above are diffs against `_COMMON_DEFAULTS` plus their family's
    defaults, which is what keeps them readable -- but every reader (and the
    cache fingerprint in `samplebank`, which folds this dict) sees whole,
    self-contained dictionaries, so a lookup can never depend on which keys a
    particular voicing happened to spell out.
    """
    out: dict[str, dict] = {}
    for name, spec in specs.items():
        family = spec.get("family", _COMMON_DEFAULTS["family"])
        merged = dict(_COMMON_DEFAULTS)
        merged.update(_STRING_DEFAULTS if family == STRING else _ELECTRIC_DEFAULTS)
        merged.update(spec)
        out[name] = merged
    return out


