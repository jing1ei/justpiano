"""
Physically-inspired tone generator for the five instruments Just Piano offers.

Every note is synthesised offline (once, then disk-cached) from a modal model:
a set of decaying sinusoids whose frequencies, levels and decay rates come from
the mechanics of the instrument that is being imitated. Nothing here is a
recording -- there is no sample library to download, and the .app carries no
audio at all.

Two families share one summation kernel (`_sum_partials`), because the arithmetic
of "add up a few hundred exponentially decaying, slightly detuned sinusoids" is
the same either way; what differs is where the numbers come from.

**Struck strings** (`grand`, `upright`, `felt`) -- a string plus the soundboard
that radiates it:

  * inharmonic partial series      f_n = n*f0*sqrt(1 + B*n^2), B spanning
                                   ~3e-5 (A0) to ~3e-2 (C8), scaled per voicing
                                   (an upright's short bass strings are far more
                                   inharmonic than a concert grand's)
  * measured spectral envelope     -6 dB/octave (grand) over the partial series
  * soundboard radiation           modal peaks near 50/80/120 Hz and a 12
                                   dB/octave roll-off below a per-voicing corner,
                                   so the bass fundamental is 10-20 dB *weaker*
                                   than partials 2-4, as on a real instrument
  * hammer strike-position comb    |sin(pi*n*p)|, p ~ 1/7 in the mid range,
                                   which is why the 7th partial is weak
  * per-partial two-stage decay    T60 ~ 1/f, knee at -25 dB, stage-2 T60 3x
                                   stage-1 (vertical->horizontal polarisation)
  * true unison choirs             1 string A0-E1, 2 up to B2, 3 above, all
                                   sharing one launch phase, detuned 0.5-2 ct
  * stretch tuning                 octave widening derived from the model's own
                                   inharmonicity, so partial 2 of a key lands on
                                   partial 1 of the key an octave up. Nearly all
                                   of it is treble (C8 ends ~42 cents sharp of
                                   equal temperament); A4 sounds at 440.000
  * mechanical noise               hammer strike, key-bed thump, damper lift,
                                   all rung through the body

**Struck bars behind a pickup** (`rhodes`, `wurlitzer`) -- an electric piano is
not a string instrument and modelling it as one is why most synthesised Rhodes
patches sound like a filtered organ. What is actually vibrating is a stiff
cantilever, and what you hear is a pickup's non-linear view of it:

  * bending modes, not harmonics   a clamped-free bar rings at 1 : 6.27 : 17.55 :
                                   34.4 -- wildly inharmonic. Those upper modes
                                   are the "tine bark", they are what a DX7
                                   E.PIANO patch is imitating with a modulator at
                                   ratio 18, and they die in a few hundred ms
                                   while the fundamental sings on.
  * a harmonic series on top       generated by the pickup, not by the bar: the
                                   magnetic (Rhodes) or electrostatic (Wurlitzer)
                                   transfer is non-linear, so a nearly sinusoidal
                                   motion comes out with harmonics. Harmonic n
                                   grows as the n-th power of the excursion and
                                   therefore decays n times faster -- which the
                                   T60 ~ 1/f law reproduces for free, and which is
                                   why an electric piano *purifies* as it decays.
  * a tuned partner               the Rhodes tine is one arm of an asymmetric fork
                                   (tine + tonebar); the pair beats slowly. The
                                   Wurlitzer's lead-loaded reed beats far less.
  * a pickup non-linearity        an asymmetric (even-harmonic) term for the way
                                   the field falls off across the swing, then a
                                   symmetric saturation for the overdrive. The
                                   Wurlitzer's electrostatic pickup runs at 170 V
                                   across a tiny gap and is the more violent of
                                   the two: that is the famous "bark".

Two velocity layers ("soft" / "hard") are rendered per note and cross-faded at
play time, so timbre gets brighter as you hit harder -- not just louder. Both
layers share the same random phases so the cross-fade is a clean spectral morph
rather than a chorus-y phase mush.
"""

